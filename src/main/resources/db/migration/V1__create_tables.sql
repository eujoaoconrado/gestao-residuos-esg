-- =====================================================================
-- V1: Criacao das tabelas do dominio Gestao de Residuos e Reciclagem
-- =====================================================================

CREATE TABLE USUARIOS (
    ID_USUARIO   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME         VARCHAR2(100) NOT NULL,
    EMAIL        VARCHAR2(150) NOT NULL,
    SENHA        VARCHAR2(255) NOT NULL,
    ROLE         VARCHAR2(20)  NOT NULL,
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ROLE CHECK (ROLE IN ('USER','ADMIN'))
);

CREATE TABLE EMPRESAS (
    ID_EMPRESA     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME           VARCHAR2(150) NOT NULL,
    CNPJ           VARCHAR2(18)  NOT NULL,
    ENDERECO       VARCHAR2(200),
    TELEFONE       VARCHAR2(20),
    DATA_CADASTRO  TIMESTAMP     NOT NULL,
    CONSTRAINT UK_EMPRESAS_CNPJ UNIQUE (CNPJ)
);

CREATE TABLE PONTOS_COLETA (
    ID_PONTO              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                  VARCHAR2(100)  NOT NULL,
    ENDERECO              VARCHAR2(200)  NOT NULL,
    TIPO_RESIDUO          VARCHAR2(20)   NOT NULL,
    CAPACIDADE_MAXIMA_KG  NUMBER(10,2)   NOT NULL,
    NIVEL_ATUAL_KG        NUMBER(10,2)   DEFAULT 0 NOT NULL,
    ID_EMPRESA            NUMBER         NOT NULL,
    CONSTRAINT FK_PONTOS_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESAS(ID_EMPRESA),
    CONSTRAINT CK_PONTOS_TIPO CHECK (TIPO_RESIDUO IN ('PLASTICO','PAPEL','VIDRO','METAL','ORGANICO','ELETRONICO')),
    CONSTRAINT CK_PONTOS_CAPACIDADE CHECK (CAPACIDADE_MAXIMA_KG > 0),
    CONSTRAINT CK_PONTOS_NIVEL CHECK (NIVEL_ATUAL_KG >= 0)
);

CREATE TABLE RESIDUOS (
    ID_RESIDUO    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO          VARCHAR2(20)   NOT NULL,
    DESCRICAO     VARCHAR2(300),
    PESO_KG       NUMBER(10,2)   NOT NULL,
    DATA_COLETA   TIMESTAMP      NOT NULL,
    ID_PONTO      NUMBER         NOT NULL,
    CONSTRAINT FK_RESIDUOS_PONTO FOREIGN KEY (ID_PONTO) REFERENCES PONTOS_COLETA(ID_PONTO),
    CONSTRAINT CK_RESIDUOS_TIPO CHECK (TIPO IN ('PLASTICO','PAPEL','VIDRO','METAL','ORGANICO','ELETRONICO')),
    CONSTRAINT CK_RESIDUOS_PESO CHECK (PESO_KG > 0)
);

CREATE TABLE COLETAS (
    ID_COLETA       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_COLETA     TIMESTAMP     NOT NULL,
    PESO_TOTAL_KG   NUMBER(10,2),
    STATUS          VARCHAR2(20)  NOT NULL,
    ID_PONTO        NUMBER        NOT NULL,
    OBSERVACOES     VARCHAR2(500),
    CONSTRAINT FK_COLETAS_PONTO FOREIGN KEY (ID_PONTO) REFERENCES PONTOS_COLETA(ID_PONTO),
    CONSTRAINT CK_COLETAS_STATUS CHECK (STATUS IN ('AGENDADA','REALIZADA','CANCELADA'))
);

-- indices auxiliares pra acelerar buscas frequentes
CREATE INDEX IX_PONTOS_EMPRESA   ON PONTOS_COLETA(ID_EMPRESA);
CREATE INDEX IX_RESIDUOS_TIPO    ON RESIDUOS(TIPO);
CREATE INDEX IX_RESIDUOS_PONTO   ON RESIDUOS(ID_PONTO);
CREATE INDEX IX_COLETAS_STATUS   ON COLETAS(STATUS);
CREATE INDEX IX_COLETAS_PONTO    ON COLETAS(ID_PONTO);
